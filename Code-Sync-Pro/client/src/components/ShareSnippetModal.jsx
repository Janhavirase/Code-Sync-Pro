import React, { useState, useRef } from 'react';
import html2canvas from 'html2canvas';
import toast from 'react-hot-toast';

const ShareSnippetModal = ({ isOpen, onClose, code, language }) => {
    const [isUploading, setIsUploading] = useState(false);
    const [shareUrl, setShareUrl] = useState('');
    const snippetRef = useRef(null);

    if (!isOpen) return null;

    const captureAndUpload = async () => {
        setIsUploading(true);
        try {
            // 1. Generate Image from DOM
            const canvas = await html2canvas(snippetRef.current, {
                backgroundColor: null,
                scale: 2 // High resolution
            });

            // 2. Convert Canvas to Blob
            canvas.toBlob(async (blob) => {
                // 3. Prepare FormData for Cloudinary
                const formData = new FormData();
                formData.append('file', blob);
                
                // ⚠️ REPLACE THESE WITH YOUR ACTUAL CLOUDINARY DETAILS
                formData.append('upload_preset', 'codesync_snippets'); 
                formData.append('cloud_name', 'dyviw3dxo'); 

                // 4. Upload to Cloudinary
                const res = await fetch('https://api.cloudinary.com/v1_1/dyviw3dxo/image/upload', {
                    method: 'POST',
                    body: formData
                });

                const data = await res.json();
                
                if (data.secure_url) {
                    setShareUrl(data.secure_url);
                    await navigator.clipboard.writeText(data.secure_url);
                    toast.success('Link copied to clipboard!');
                } else {
                    throw new Error('Upload failed');
                }
                setIsUploading(false);
            }, 'image/png');

        } catch (error) {
            console.error(error);
            toast.error('Failed to share snippet');
            setIsUploading(false);
        }
    };

    return (
        <div className="fixed inset-0 bg-black/80 z-50 flex items-center justify-center p-4">
            <div className="bg-[#1e1e1e] rounded-xl w-full max-w-2xl border border-[#333] shadow-2xl flex flex-col max-h-[90vh]">
                
                {/* Header */}
                <div className="p-4 border-b border-[#333] flex justify-between items-center">
                    <h2 className="text-xl font-bold text-white">Share Snippet</h2>
                    <button onClick={onClose} className="text-gray-400 hover:text-white">✕</button>
                </div>

                {/* Preview Area (Scrollable) */}
                <div className="p-6 overflow-y-auto bg-[#111] flex justify-center">
                    {/* This div is what we screenshot */}
                    <div 
                        ref={snippetRef} 
                        className="bg-[#282c34] p-8 rounded-lg shadow-2xl min-w-[500px]"
                        style={{ fontFamily: 'Fira Code, monospace' }}
                    >
                        {/* Fake Mac Window Controls */}
                        <div className="flex gap-2 mb-4">
                            <div className="w-3 h-3 rounded-full bg-red-500" />
                            <div className="w-3 h-3 rounded-full bg-yellow-500" />
                            <div className="w-3 h-3 rounded-full bg-green-500" />
                        </div>
                        {/* Code Content */}
                        <div className="text-gray-300 whitespace-pre-wrap text-sm">
                            {code}
                        </div>
                        <div className="mt-4 text-xs text-gray-500 text-right">
                            Generated by CodeSync Pro
                        </div>
                    </div>
                </div>

                {/* Footer Controls */}
                <div className="p-4 border-t border-[#333] flex justify-end gap-3 bg-[#1e1e1e]">
                    {shareUrl ? (
                        <div className="flex-1 flex items-center gap-2 bg-[#111] px-3 rounded border border-green-500/30">
                            <span className="text-green-400 text-sm truncate">{shareUrl}</span>
                            <button 
                                onClick={() => {
                                    navigator.clipboard.writeText(shareUrl);
                                    toast.success('Copied!');
                                }} 
                                className="text-xs bg-green-600 px-2 py-1 rounded text-white"
                            >
                                Copy
                            </button>
                        </div>
                    ) : (
                        <button onClick={onClose} className="px-4 py-2 text-gray-400 hover:text-white">Cancel</button>
                    )}
                    
                    {!shareUrl && (
                        <button 
                            onClick={captureAndUpload} 
                            disabled={isUploading}
                            className="bg-blue-600 hover:bg-blue-700 text-white px-6 py-2 rounded-md font-bold disabled:opacity-50"
                        >
                            {isUploading ? 'Generating...' : '📸 Share Image'}
                        </button>
                    )}
                </div>
            </div>
        </div>
    );
};

export default ShareSnippetModal;